#!/usr/bin/env bash
# Extract Bridge IMAP credentials from the protonmail-bridge volume and sync to n8n.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

CREDS_FILE="$ROOT/compose/protonmail-bridge/credentials.env"
BRIDGE_WAS_RUNNING=0

log() { printf '[proton-bridge] %s\n' "$1"; }
die() { printf '[proton-bridge] ERROR: %s\n' "$1" >&2; exit 1; }

[[ -f .env ]] || die "Missing .env — run ./scripts/setup.sh --mail first"

# shellcheck disable=SC1091
source .env

[[ -n "${PROTON_BRIDGE_IMAGE:-}" ]] || die "PROTON_BRIDGE_IMAGE is not set — run ./scripts/setup.sh --mail"

compose_mail() {
  docker compose --profile mail "$@"
}

if docker compose --profile mail ps --status running --services 2>/dev/null | grep -qx protonmail-bridge; then
  log "Stopping protonmail-bridge (Bridge lock file must be free for credential extraction)"
  compose_mail stop protonmail-bridge
  BRIDGE_WAS_RUNNING=1
fi

log "Reading Bridge credentials from volume..."
cli_output="$(compose_mail run --rm --entrypoint /bin/bash protonmail-bridge \
  -c 'printf "info\nexit\n" | protonmail-bridge --cli 2>&1' || true)"

if [[ -z "$cli_output" ]]; then
  die "Bridge CLI returned no output — run ./scripts/proton-bridge-init.sh first"
fi

if grep -qi 'No active accounts' <<<"$cli_output"; then
  die "No active Bridge accounts — run ./scripts/proton-bridge-init.sh and complete login"
fi

imap_user="$(grep -Ei '^\s*Username:\s*' <<<"$cli_output" | head -1 | sed -E 's/^[[:space:]]*[Uu]sername:[[:space:]]*//')"
imap_password="$(grep -Ei '^\s*Password:\s*' <<<"$cli_output" | head -1 | sed -E 's/^[[:space:]]*[Pp]assword:[[:space:]]*//')"

[[ -n "$imap_user" && -n "$imap_password" ]] || die "Could not parse Username/Password from Bridge info output"

new_content="# Auto-generated by scripts/sync-proton-bridge-credentials.sh — do not edit manually
PROTON_BRIDGE_IMAP_USER=${imap_user}
PROTON_BRIDGE_IMAP_PASSWORD=${imap_password}
"

if [[ -f "$CREDS_FILE" ]] && cmp -s <(printf '%s' "$new_content") "$CREDS_FILE"; then
  log "Bridge credentials unchanged"
else
  printf '%s' "$new_content" > "$CREDS_FILE"
  log "Wrote $CREDS_FILE"
fi

set -a
# shellcheck disable=SC1091
source "$CREDS_FILE"
# shellcheck disable=SC1091
source <(grep -E '^(N8N_ENCRYPTION_KEY|LIGHTRAG_API_KEY|NEO4J_PASSWORD|NEO4J_USERNAME|PROTON_BRIDGE_HOST|PROTON_BRIDGE_IMAP_PORT|PROTON_BRIDGE_IMAP_SECURE|PROTON_BRIDGE_ALLOW_UNAUTHORIZED_CERTS)=' .env | sed 's/^/export /')
set +a

node scripts/generate-n8n-credentials.js
log "Regenerated n8n demo credentials (includes Proton Mail Bridge if configured)"

if [[ "$BRIDGE_WAS_RUNNING" -eq 1 ]]; then
  log "Restarting protonmail-bridge"
  compose_mail up -d protonmail-bridge
fi

if docker compose ps --status running --services 2>/dev/null | grep -qx n8n; then
  cat <<'EOF'

n8n is already running. Re-import credentials if this is not a first boot:

  docker compose run --rm --entrypoint /bin/sh n8n-import -c \
    'n8n import:credentials --separate --input=/demo-data/credentials'

EOF
fi
